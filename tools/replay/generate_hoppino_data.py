"""Generate the flash-resident sensor table; recorded navigation outputs are excluded."""
import argparse
import hashlib
import math
from pathlib import Path
import struct
from replay_navigation import ROOT,DEFAULT_INPUT,load_sensor_samples


OUTPUT=ROOT/'src/simulation/data/HoppinoData.inc'


def literal(value):
    value=struct.unpack('<f',struct.pack('<f',value))[0]
    if math.isnan(value): return 'std::numeric_limits<float>::quiet_NaN()'
    if math.isinf(value): return ('-' if value<0 else '')+'std::numeric_limits<float>::infinity()'
    text=format(value,'.9g')
    if not any(c in text for c in '.eE'): text+='.0'
    return text+'f'


def generate():
    rows,samples,reference,hz=load_sensor_samples(DEFAULT_INPUT)
    origin=samples[0][0]; duration=samples[-1][0]-origin
    lines=['// Generated by tools/replay/generate_hoppino_data.py; do not edit.',
           '// Source: datasets/hoppino_VOLO_UFFICIALE.csv; SHA256 '+hashlib.sha256(DEFAULT_INPUT.read_bytes()).hexdigest(),
           '// BODY IMU in SI units; pressure Pa; temperature Celsius; relative timestamps ms.',
           f'constexpr uint32_t NominalPeriodUs = {round(1000000/hz)};',
           f'constexpr uint32_t DurationMs = {duration};',
           f'const float NominalHz = {literal(hz)};',f'const float ReferenceAltitude = {literal(reference)};',
           'const LoggedSample HoppinoSamples[] = {']
    for row,(stamp,values) in zip(rows,samples):
        values=[literal(value) for value in (*values,float(row.get('temp') or 'nan'))]
        lines.append('  {'+str(stamp-origin)+', {'+', '.join(values[:3])+'}, {'+', '.join(values[3:6])+'}, '+', '.join(values[6:])+'},')
    lines.extend(['};','static_assert(sizeof(LoggedSample)==36,"Unexpected Hoppino sample layout");',''])
    return '\n'.join(lines)


def main():
    parser=argparse.ArgumentParser(description=__doc__); parser.add_argument('--check',action='store_true')
    args=parser.parse_args(); generated=generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding='utf-8')!=generated:
            parser.exit(1,'Hoppino table is stale; run python tools/replay/generate_hoppino_data.py\n')
        print('Hoppino sensor table matches the repository CSV.')
    else:
        OUTPUT.parent.mkdir(parents=True,exist_ok=True); OUTPUT.write_text(generated,encoding='utf-8',newline='\n')
        print('Generated '+str(OUTPUT.relative_to(ROOT)))


if __name__=='__main__': main()
